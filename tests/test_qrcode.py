def render(matrix, path, scale=4, quiet=4):
    """The matrix as a PNG, as the dialog draws it: dark modules on white, quiet zone around."""
    size = (len(matrix) + 2 * quiet) * scale
    surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, size, size)
    cr = cairo.Context(surface)
    cr.set_source_rgb(1, 1, 1)
    cr.paint()
    cr.set_source_rgb(0, 0, 0)
    for row, line in enumerate(matrix):
        for col, dark in enumerate(line):
            if dark:
                cr.rectangle((col + quiet) * scale, (row + quiet) * scale, scale, scale)
    cr.fill()
    surface.write_to_png(path)


class Golden(unittest.TestCase):
    def test_matches_known_matrices(self):
        for text, expected in GOLDEN.items():
            with self.subTest(text=text[:30]):
                matrix = qrcode.encode(text)
                self.assertEqual("\n".join("".join(map(str, row)) for row in matrix), expected)

    def test_too_long(self):
        with self.assertRaises(ValueError):
            qrcode.encode("x" * 214)


@unittest.skipUnless(shutil.which("zbarimg"), "zbarimg is not installed")
class Decodes(unittest.TestCase):
    def test_rendered_codes_decode(self):
        """PNGs of the golden matrices and of every version's shortest code round-trip through zbarimg."""
        with tempfile.TemporaryDirectory() as tmp:
            texts = list(GOLDEN) + ["x" * n for n in (1, 15, 27, 43, 63, 85, 107, 123, 153, 181, 213)]
            for i, text in enumerate(texts):
                with self.subTest(length=len(text)):
                    path = os.path.join(tmp, f"qr{i}.png")
                    render(qrcode.encode(text), path)
                    done = subprocess.run(["zbarimg", "--quiet", "--raw", path], capture_output=True)
                    self.assertEqual(done.stdout, text.encode() + b"\n")


